#!/usr/bin/env bash
# Smoke test for the mkDsh wrapper's provision_node_modules (lib/mk-dsh.nix).
#
# Runs the REAL wrapper (built around a fake core/plugins set, flake output
# .#dsh-smoke) against throwaway DSH_HOMEs and asserts:
#   1. fresh provision: profiles/<name>/node_modules is a real dir; bare
#      entries are store symlinks; @scope entries are real dirs holding
#      per-package store symlinks; headless is provisioned too
#   2. devMounts: mounted entries point at their out-of-store src
#      (bare name AND scoped package), and dsh's manifest patchReload is
#      baked per profile name (web=live, headless=startup)
#   3. re-run is idempotent and keeps runtime artifacts a la rc.1 healing
#   4. legacy single store symlink at node_modules migrates to a real dir
#   5. a non-store symlink at node_modules → CONFLICT, nothing destroyed
#   6. real-dir entry → WARN + kept (pnpm/healing authority);
#      real-file entry → CONFLICT, file kept
#   7. dsh-unlink removes managed links, keeps real entries, never deletes
#      a real package.json (dsh runtime state)
#
# Usage: bash tests/provision-node_modules.bash [<dsh-bin-dir> [<dsh-unlink-bin-dir>]]
#   Without an argument the wrapper is built via `nix build .#dsh-smoke`
#   (the same path `nix flake check` uses for checks.wrapper-smoke).

set -euo pipefail
cd "$(dirname "$0")/.."

die() { echo "FAIL: $*" >&2; exit 1; }
ok()  { echo "ok: $*"; }

assert_dir() { [[ -d $1 && ! -L $1 ]] || die "$1: not a real directory"; }
assert_gone() { [[ ! -e $1 && ! -L $1 ]] || die "$1: still exists"; }
assert_link_to() { # LINK EXPECTED (exact target)
  [[ -L $1 ]] || die "$1: not a symlink"
  local t; t="$(readlink -f "$1")"
  [[ "$t" == "$2" ]] || die "$1: resolves to '$t', expected '$2'"
}
assert_link_under() { # LINK BASENAME (resolved target under /nix/store)
  [[ -L $1 ]] || die "$1: not a symlink"
  local t; t="$(readlink -f "$1")"
  [[ "$t" == /nix/store/* ]] || die "$1: resolved target '$t' not under /nix/store"
  [[ "$(basename "$t")" == "$2" ]] || die "$1: resolved target '$t' basename is not '$2'"
}

wrapper_bin="${1:-}"
if [[ -z "$wrapper_bin" ]]; then
  echo "building .#dsh-smoke ..."
  wrapper_bin="$(nix build .#dsh-smoke --no-link --print-out-paths)/bin"
fi
DSH="$wrapper_bin/dsh"
[[ -x $DSH ]] || die "wrapper not executable: $DSH"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# --- 1+2: fresh provision ---------------------------------------------------
home="$tmp/home1"
out="$(DSH_HOME="$home" "$DSH" 2>&1)" || die "first launch failed: $out"
nm="$home/profiles/web/node_modules"
assert_dir "$nm"
assert_link_under "$nm/core-dep" "core-dep"
assert_link_to "$nm/dsh-fake-extra" "/tmp/dsh-smoke-src-extra"
assert_dir "$nm/@fake"
assert_link_under "$nm/@fake/dep" "dep"
assert_link_to "$nm/dsh-fake-bare" "/tmp/dsh-smoke-src-bare"
assert_link_to "$nm/@fake/scope-pkg" "/tmp/dsh-smoke-src-scoped"
assert_dir "$home/profiles/headless/node_modules"
pkg="$home/profiles/web/package.json"
[[ -L $pkg ]] || die "web package.json is not a store symlink"
json_ok() { # FILE EXPECTED — the manifest dsh parses must be structurally sane JSON
  grep -q "\"patchReload\": \"$2\"" "$1" || die "$1: no baked patchReload $2"
  [[ "$(grep -o '{' "$1" | wc -l)" -eq "$(grep -o '}' "$1" | wc -l)" ]] || die "$1: braces unbalanced (invalid JSON)"
}
json_ok "$pkg" live
json_ok "$home/profiles/headless/package.json" startup
ok "fresh provision: real dir, bare + scoped links, devMounts, both profiles, baked patchReload"

# --- 3: healing-style artifacts survive an idempotent re-run ----------------
mkdir -p "$tmp/owned/node_modules" "$nm/@codemirror"
ln -s "$tmp/owned/node_modules/foo" "$nm/@codemirror/foo"
ln -s "$tmp/owned/node_modules/foo" "$nm/heal-pkg"
out="$(DSH_HOME="$home" "$DSH" 2>&1)" || die "second launch failed: $out"
[[ "$out" != *CONFLICT* ]] || die "re-run hit CONFLICT: $out"
assert_link_to "$nm/@codemirror/foo" "$tmp/owned/node_modules/foo"
assert_link_to "$nm/heal-pkg" "$tmp/owned/node_modules/foo"
assert_link_to "$nm/@fake/scope-pkg" "/tmp/dsh-smoke-src-scoped"
ok "re-run idempotent; healing-style artifacts kept"

# --- 4: legacy single store symlink migrates to a real dir ------------------
home2="$tmp/home2"
nm_store="$(dirname "$(dirname "$(readlink "$nm/@fake/dep")")")" # …-node_modules
mkdir -p "$home2/profiles/web"
ln -s "$nm_store" "$home2/profiles/web/node_modules"
out="$(DSH_HOME="$home2" "$DSH" 2>&1)" || die "migration launch failed: $out"
assert_dir "$home2/profiles/web/node_modules"
assert_link_under "$home2/profiles/web/node_modules/core-dep" "core-dep"
[[ "$out" == *migrated* ]] || die "expected migration log, got: $out"
ok "legacy store symlink migrated to real per-entry-linked dir"

# --- 5: non-store symlink at node_modules → CONFLICT, data intact -----------
home3="$tmp/home3"
mkdir -p "$home3/profiles/web" "$tmp/userdata"
echo precious > "$tmp/userdata/data.yaml"
ln -s "$tmp/userdata" "$home3/profiles/web/node_modules"
out="$(DSH_HOME="$home3" "$DSH" 2>&1)" && die "expected CONFLICT exit, got success: $out"
[[ "$out" == *CONFLICT* ]] || die "expected CONFLICT message: $out"
[[ "$(cat "$tmp/userdata/data.yaml")" == precious ]] || die "user data behind the symlink was destroyed"
ok "non-store node_modules symlink refused (CONFLICT), user data intact"

# --- 6a: real-dir entry → WARN + kept ---------------------------------------
home4="$tmp/home4"
nm4="$home4/profiles/web/node_modules"
mkdir -p "$nm4/core-dep"
echo '{}' > "$nm4/core-dep/package.json"
out="$(DSH_HOME="$home4" "$DSH" 2>&1)" || die "launch failed with real-dir entry: $out"
[[ "$out" == *WARN* ]] || die "expected WARN for real-dir entry, got: $out"
[[ -f "$nm4/core-dep/package.json" ]] || die "real-dir entry was clobbered"
assert_link_under "$nm4/@fake/dep" "dep"
ok "real-dir entry kept with WARN; sibling entries still provisioned"

# --- 6b: real-file entry → CONFLICT, file kept ------------------------------
home5="$tmp/home5"
nm5="$home5/profiles/web/node_modules"
mkdir -p "$nm5"
echo stray > "$nm5/core-dep"
out="$(DSH_HOME="$home5" "$DSH" 2>&1)" && die "expected CONFLICT exit for stray file, got success"
[[ "$out" == *CONFLICT* ]] || die "expected CONFLICT message: $out"
[[ "$(cat "$nm5/core-dep")" == stray ]] || die "stray file was destroyed"
ok "real-file entry refused (CONFLICT), file intact"

# --- 7: dsh-unlink removes managed links, keeps real state ------------------
unlink_bin="${2:-$(nix build .#dsh-smoke-unlink --no-link --print-out-paths)/bin}"
DSH_UNLINK="$unlink_bin/dsh-unlink"
[[ -x $DSH_UNLINK ]] || die "dsh-unlink missing: $DSH_UNLINK"
DSH_HOME="$home" "$DSH_UNLINK" >/dev/null 2>&1 || die "dsh-unlink failed"
assert_gone "$nm/heal-pkg"
assert_gone "$nm/@codemirror"
assert_gone "$nm"
assert_gone "$home/profiles/web/package.json"
[[ -f "$home/settings.yaml" || ! -e "$home/settings.yaml" ]] # trivial; settings untouched path
ok "dsh-unlink: managed links removed, real dirs left alone when non-empty"

echo "ALL PASS"
